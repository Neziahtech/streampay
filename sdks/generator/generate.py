def generate_rust() -> str:
    lines: list[str] = [HEADER.format(fingerprint=FINGERPRINT), ""]
    lines += [
        "//! Generated contract bindings: types, entrypoint arguments, event",
        "//! decoders, and result decoders. Regenerate with `make -C sdks generate`.",
        "",
        "use std::collections::BTreeMap;",
        "",
        "use stellar_xdr::{ContractEvent, ContractEventBody, ScVal};",
        "",
        "use crate::{",
        "    address_scval, scval_bool, scval_i128, scval_to_address, scval_to_bool,",
        "    scval_to_i128, scval_to_struct, scval_to_u32, scval_to_u64, scval_to_void,",
        "    scval_u32, scval_u64, SdkError,",
        "};",
        "",
        "/// Looks up a contract-type field by symbol name.",
        "fn field<'a>(",
        "    values: &'a BTreeMap<String, ScVal>,",
        "    name: &str,",
        ") -> Result<&'a ScVal, SdkError> {",
        "    values",
        "        .get(name)",
        "        .ok_or_else(|| SdkError::Decode(format!(\"struct is missing field `{name}`\")))",
        "}",
        "",
        f'pub const SPEC_FINGERPRINT: &str = "{FINGERPRINT}";',
        f'pub const CONTRACT_VERSION: &str = "{SPEC["contract"]["version"]}";',
    ]
    for name, constant in SPEC["constants"].items():
        lines.append(f"pub const {name}: {constant['type']} = {constant['value']};")
    lines.append("")

    for function in SPEC["functions"]:
        const = "METHOD_" + function["name"].upper()
        lines.append(f'pub const {const}: &str = "{function["name"]}";')
    lines.append("")

    # Enums.
    for enum in SPEC["enums"]:
        lines.append("#[derive(Copy, Clone, Debug, PartialEq, Eq)]")
        lines.append(f"pub enum {enum['name']} {{")
        for case in enum["cases"]:
            lines.append(f"    {case['name']},")
        lines.append("}")
        lines.append("")
        lines.append(f"impl {enum['name']} {{")
        lines.append("    pub fn from_scval(value: &ScVal) -> Result<Self, SdkError> {")
        lines.append("        match scval_to_u32(value)? {")
        for case in enum["cases"]:
            lines.append(f"            {case['value']} => Ok(Self::{case['name']}),")
        lines.append("            other => Err(SdkError::Decode(format!(")
        lines.append(
            f'                "unknown {enum["name"]} discriminant {{other}}"'
        )
        lines.append("            ))),")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    pub fn as_str(&self) -> &'static str {")
        lines.append("        match self {")
        for case in enum["cases"]:
            lines.append(f'            Self::{case["name"]} => "{case["name"]}",')
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")

    # Structs.
    for struct in SPEC["structs"]:
        lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
        lines.append(f"pub struct {struct['name']} {{")
        for field in struct["fields"]:
            lines.append(f"    pub {field['name']}: {rust_type(field['type'])},")
        lines.append("}")
        lines.append("")
        lines.append(f"impl {struct['name']} {{")
        lines.append("    pub fn from_scval(value: &ScVal) -> Result<Self, SdkError> {")
        lines.append("        let fields = scval_to_struct(value)?;")
        lines.append("        Ok(Self {")
        for field in struct["fields"]:
            lines.append(f"            {field['name']}: SCOPE(PLACEHOLDER),")
        lines.append("        })")
        lines.append("    }")
        lines.append("}")
        lines.append("")
    # Fill struct decoders with the safe field accessor (kept separate so the
    # generated body stays readable).
    rendered = "\n".join(lines)
    for struct in SPEC["structs"]:
        body = []
        for field in struct["fields"]:
            body.append(
                f"            {field['name']}: {rust_from_scval(field['type'], 'field(&fields, \"' + field['name'] + '\")?')},"
            )
        placeholder = "\n".join(
            f"            {field['name']}: SCOPE(PLACEHOLDER),"
            for field in struct["fields"]
        )
        rendered = rendered.replace(placeholder, "\n".join(body), 1)
        helper = (
            "impl " + struct["name"] + " {\n"
            "    pub fn from_scval(value: &ScVal) -> Result<Self, SdkError> {\n"
            "        let fields = scval_to_struct(value)?;\n"
            "        Ok(Self {\n"
        )
        rendered = rendered.replace(
            helper,
            helper
            + "        // Missing fields are a decode error, never a silent default.\n",
            1,
        )
    lines = rendered.split("\n")

    # Argument structs.
    for function in SPEC["functions"]:
        args_name = pascal(function["name"]) + "Args"
        lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
        lines.append(f"pub struct {args_name} {{")
        for arg in function["args"]:
            lines.append(f"    pub {arg['name']}: {rust_type(arg['type'])},")
        lines.append("}")
        lines.append("")
        lines.append(f"impl {args_name} {{")
        lines.append("    pub fn to_scvals(&self) -> Result<Vec<ScVal>, SdkError> {")
        lines.append("        Ok(vec![")
        for arg in function["args"]:
            lines.append(f"            {rust_to_scval(arg['type'], 'self.' + arg['name'])},")
        lines.append("        ])")
        lines.append("    }")
        lines.append("}")
        lines.append("")

    # Events.
    for event in SPEC["events"]:
        lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
        lines.append(f"pub struct {event['name']} {{")
        for field in event["topicFields"] + event["dataFields"]:
            lines.append(f"    pub {field['name']}: {rust_type(field['type'])},")
        lines.append("}")
        lines.append("")
    variants = "\n".join(f"    {e['name']}({e['name']})," for e in SPEC["events"])
    lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
    lines.append("pub enum Event {")
    lines.append(variants)
    lines.append("}")
    lines.append("")
    lines.append("impl Event {")
    lines.append("    /// Decodes a contract event, or `None` for events not emitted by")
    lines.append("    /// StreamPay (other contracts on the same ledger).")
    lines.append("    pub fn decode(event: &ContractEvent) -> Result<Option<Self>, SdkError> {")
    lines.append("        let ContractEventBody::V0(body) = &event.body;")
    lines.append("        let Some(ScVal::Symbol(name)) = body.topics.first() else {")
    lines.append("            return Ok(None);")
    lines.append("        };")
    lines.append("        let name = name.0.to_string();")
    lines.append("        let topic = |index: usize| -> Result<&ScVal, SdkError> {")
    lines.append("            body.topics.get(index).ok_or_else(|| {")
    lines.append("                SdkError::Decode(format!(\"event `{name}` is missing topic {index}\"))")
    lines.append("            })")
    lines.append("        };")
    lines.append("        match name.as_str() {")
    for event in SPEC["events"]:
        lines.append(f'            "{event["topic"]}" => {{')
        lines.append(f"                let data = scval_to_struct(&body.data)?;")
        lines.append(f"                Ok(Some(Self::{event['name']}({event['name']} {{")
        index = 1
        for field in event["topicFields"]:
            lines.append(
                f"                    {field['name']}: {rust_from_scval(field['type'], 'topic(' + str(index) + ')?')},"
            )
            index += 1
        for field in event["dataFields"]:
            lines.append(
                f"                    {field['name']}: {rust_from_scval(field['type'], 'field(&data, \"' + field['name'] + '\")?')},"
            )
        lines.append("                })))")
        lines.append("            }")
    lines.append("            _ => Ok(None),")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Errors.
    lines.append("#[derive(Copy, Clone, Debug, PartialEq, Eq)]")
    lines.append("pub enum StreamError {")
    for error in SPEC["errors"]:
        lines.append(f"    {error['name']},")
    lines.append("}")
    lines.append("")
    lines.append("impl StreamError {")
    lines.append("    pub fn code(&self) -> u32 {")
    lines.append("        match self {")
    for error in SPEC["errors"]:
        lines.append(f"            Self::{error['name']} => {error['code']},")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn name(&self) -> &'static str {")
    lines.append("        match self {")
    for error in SPEC["errors"]:
        lines.append(f'            Self::{error["name"]} => "{error["name"]}",')
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn from_code(code: u32) -> Option<Self> {")
    lines.append("        match code {")
    for error in SPEC["errors"]:
        lines.append(f"            {error['code']} => Some(Self::{error['name']}),")
    lines.append("            _ => None,")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Result decoders.
    for function in SPEC["functions"]:
        name = "decode_" + function["name"] + "_result"
        returns = function["returns"]
        lines.append(
            f"pub fn {name}(value: &ScVal) -> Result<{rust_type(returns)}, SdkError> {{"
        )
        if returns == "void":
            lines.append("    scval_to_void(value)")
        elif isinstance(returns, dict) and "vec" in returns:
            inner = returns["vec"]
            lines.append("    let ScVal::Vec(Some(items)) = value else {")
            lines.append(
                f'        return Err(SdkError::Decode("{function["name"]}: expected a vec".into()));'
            )
            lines.append("    };")
            lines.append(f"    items.iter().map(scval_to_{inner}).collect()")
        elif returns == "Stream":
            lines.append("    Stream::from_scval(value)")
        else:
            lines.append(f"    scval_to_{returns}(value)")
        lines.append("}")
        lines.append("")

    # Function metadata (used by the conformance runner and docs).
    def spec_type(t) -> str:
        if isinstance(t, dict) and "vec" in t:
            return "vec:" + spec_type(t["vec"])
        return str(t)

    lines.append("pub struct FunctionSpec {")
    lines.append("    pub name: &'static str,")
    lines.append("    pub arg_names: &'static [&'static str],")
    lines.append("    pub arg_types: &'static [&'static str],")
    lines.append("    pub return_type: &'static str,")
    lines.append("    pub mutating: bool,")
    lines.append("}")
    lines.append("")
    lines.append("pub const FUNCTIONS: &[FunctionSpec] = &[")
    for function in SPEC["functions"]:
        args = ", ".join(f'"{a["name"]}"' for a in function["args"])
        types = ", ".join(f'"{spec_type(a["type"])}"' for a in function["args"])
        lines.append("    FunctionSpec {")
        lines.append(f'        name: "{function["name"]}",')
        lines.append(f"        arg_names: &[{args}],")
        lines.append(f"        arg_types: &[{types}],")
        lines.append(f'        return_type: "{spec_type(function["returns"])}",')
        lines.append(
            f"        mutating: {'true' if function['mutating'] else 'false'},"
        )
        lines.append("    },")
    lines.append("];")
    lines.append("")

    # Typed client methods.
    lines.append("impl<'a, T: crate::Transport> crate::Client<'a, T> {")
    for function in SPEC["functions"]:
        method = function["name"]
        returns = rust_type(function["returns"])
        lines.append(f"    /// {function['doc']}")
        if len(function["args"]) >= 7:
            lines.append("    #[allow(clippy::too_many_arguments)]")
        lines.append(f"    pub fn {method}(")
        lines.append("        &self,")
        for arg in function["args"]:
            if arg["type"] == "address":
                lines.append(f"        {arg['name']}: &str,")
            else:
                lines.append(f"        {arg['name']}: {rust_type(arg['type'])},")
        lines.append(f"    ) -> Result<{returns}, SdkError> {{")
        lines.append("        let value = self." + ("invoke" if function["mutating"] else "simulate") + "(")
        lines.append(f"            {('METHOD_' + method.upper())},")
        lines.append("            vec![")
        for arg in function["args"]:
            if arg["type"] == "address":
                lines.append(f"                address_scval({arg['name']})?,")
            else:
                lines.append(f"                {rust_to_scval(arg['type'], arg['name'])},")
        lines.append("            ],")
        lines.append("        )?;")
        lines.append(f"        decode_{method}_result(&value)")
        lines.append("    }")
        lines.append("")
    lines.append("}")
    lines.append("")

    return "\n".join(lines)


