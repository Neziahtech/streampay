#!/usr/bin/env python3
"""Generate the Rust, TypeScript, and Python StreamPay clients.

The canonical input is ``sdks/spec/streampay.spec.json``; this script is the
only place that knows how each language spells the contract surface. It is
deterministic, so ``--check`` is a valid CI gate: regeneration must be a no-op.

Usage
  python3 sdks/generator/generate.py           # write generated files
  python3 sdks/generator/generate.py --check   # fail if outputs are stale
"""
from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_contract_surface import canonical_bytes, fingerprint  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SPEC_PATH = ROOT / "sdks" / "spec" / "streampay.spec.json"
SPEC = __import__("json").loads(SPEC_PATH.read_text())
FINGERPRINT = fingerprint(SPEC)

HEADER = (
    "// @generated by sdks/generator/generate.py from "
    "sdks/spec/streampay.spec.json (sha256:{fingerprint}).\n"
    "// Do not edit by hand: change the spec, then regenerate.\n"
)
PY_HEADER = (
    "# @generated by sdks/generator/generate.py from "
    "sdks/spec/streampay.spec.json (sha256:{fingerprint}).\n"
    "# Do not edit by hand: change the spec, then regenerate.\n"
)


def snake(name: str) -> str:
    out = []
    for index, char in enumerate(name):
        if char.isupper() and index:
            out.append("_")
        out.append(char.lower())
    return "".join(out)


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(part.title() for part in parts[1:])


def pascal(name: str) -> str:
    return "".join(part.title() for part in name.split("_"))


def rust_type(t) -> str:
    if isinstance(t, dict) and "vec" in t:
        return f"Vec<{rust_type(t['vec'])}>"
    return {
        "address": "String",
        "i128": "i128",
        "u64": "u64",
        "u32": "u32",
        "bool": "bool",
        "Stream": "Stream",
        "StreamStatus": "StreamStatus",
        "void": "()",
    }[t if isinstance(t, str) else "void"]


def ts_type(t) -> str:
    if isinstance(t, dict) and "vec" in t:
        return f"{ts_type(t['vec'])}[]"
    return {
        "address": "string",
        "i128": "bigint",
        "u64": "bigint",
        "u32": "number",
        "bool": "boolean",
        "Stream": "Stream",
        "StreamStatus": "StreamStatus",
        "void": "void",
    }[t if isinstance(t, str) else "void"]


def py_type(t) -> str:
    if isinstance(t, dict) and "vec" in t:
        return f"list[{py_type(t['vec'])}]"
    return {
        "address": "str",
        "i128": "int",
        "u64": "int",
        "u32": "int",
        "bool": "bool",
        "Stream": "Stream",
        "StreamStatus": "StreamStatus",
        "void": "None",
    }[t if isinstance(t, str) else "void"]


def rust_from_scval(t, expr: str) -> str:
    if isinstance(t, dict) and "vec" in t:
        raise ValueError("vec decoding generated per function is not supported yet")
    return {
        "address": f"scval_to_address({expr})?",
        "i128": f"scval_to_i128({expr})?",
        "u64": f"scval_to_u64({expr})?",
        "u32": f"scval_to_u32({expr})?",
        "bool": f"scval_to_bool({expr})?",
        "Stream": f"Stream::from_scval({expr})?",
        "StreamStatus": f"StreamStatus::from_scval({expr})?",
    }[t]


def rust_to_scval(t, expr: str) -> str:
    return {
        "address": f"address_scval(&{expr})?",
        "i128": f"scval_i128({expr})",
        "u64": f"scval_u64({expr})",
        "u32": f"scval_u32({expr})",
        "bool": f"scval_bool({expr})",
    }[t]


