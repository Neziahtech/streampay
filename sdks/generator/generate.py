def generate_typescript() -> str:
    out: list[str] = [
        HEADER.format(fingerprint=FINGERPRINT),
        "",
        "import {",
        "  Address,",
        "  StrKey,",
        "  nativeToScVal,",
        "  scValToNative,",
        "  xdr,",
        '} from "@stellar/stellar-sdk";',
        "",
        f'export const SPEC_FINGERPRINT = "{FINGERPRINT}";',
        f'export const CONTRACT_VERSION = "{SPEC["contract"]["version"]}";',
    ]
    for name, constant in SPEC["constants"].items():
        out.append(f"export const {name} = {constant['value']};")
    out.append("")

    out.append("/** Contract method names, e.g. `METHODS.createStream`. */")
    out.append("export const METHODS = {")
    for function in SPEC["functions"]:
        out.append(f'  {camel(function["name"])}: "{function["name"]}",')
    out.append("} as const;")
    out.append("")

    for enum in SPEC["enums"]:
        out.append(f"export type {enum['name']} =")
        out.append(
            "  | " + "\n  | ".join(f'"{case["name"]}"' for case in enum["cases"]) + ";"
        )
        out.append("")
        out.append(
            f"const {snake(enum['name']).upper()}_BY_VALUE: Record<number, {enum['name']}> = {{"
        )
        for case in enum["cases"]:
            out.append(f'  {case["value"]}: "{case["name"]}",')
        out.append("};")
        out.append("")

    out.append("export type Int128 = bigint | string;")
    out.append("export type U64 = bigint | number | string;")
    out.append("")
    out.append("export interface Stream {")
    out.append("  id: bigint;")
    out.append("  sender: string;")
    out.append("  recipient: string;")
    out.append("  token: string;")
    out.append("  deposit: bigint;")
    out.append("  withdrawn: bigint;")
    out.append("  startTime: bigint;")
    out.append("  endTime: bigint;")
    out.append("  cancelable: boolean;")
    out.append("  status: StreamStatus;")
    out.append("}")
    out.append("")

    out.append("export interface CreateStreamArgs {")
    out.append("  sender: string;")
    out.append("  recipient: string;")
    out.append("  token: string;")
    out.append("  depositAmount: Int128;")
    out.append("  startTime: U64;")
    out.append("  endTime: U64;")
    out.append("  cancelable: boolean;")
    out.append("}")
    out.append("")
    for function in SPEC["functions"]:
        if function["name"] == "create_stream":
            continue
        args_name = pascal(function["name"]) + "Args"
        out.append(f"export interface {args_name} {{")
        for arg in function["args"]:
            t = arg["type"]
            ts = "Int128" if t == "i128" else ("U64" if t in ("u64", "u32") else ts_type(t))
            out.append(f"  {camel(arg['name'])}: {ts};")
        out.append("}")
        out.append("")

    out.append("export function addressToScVal(value: string): xdr.ScVal {")
    out.append("  return nativeToScVal(new Address(value), { type: \"address\" });")
    out.append("}")
    out.append("")
    out.append("function asBigInt(value: Int128 | U64, label: string): bigint {")
    out.append("  try {")
    out.append("    return BigInt(value);")
    out.append("  } catch {")
    out.append("    throw new Error(`invalid integer for ${label}: ${String(value)}`);")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("function asNative(value: xdr.ScVal): unknown {")
    out.append("  return scValToNative(value) as unknown;")
    out.append("}")
    out.append("")
    out.append("function asBigIntResult(value: xdr.ScVal, label: string): bigint {")
    out.append("  const native = asNative(value);")
    out.append("  if (typeof native !== \"bigint\") {")
    out.append("    throw new Error(`${label}: expected an integer, got ${typeof native}`);")
    out.append("  }")
    out.append("  return native;")
    out.append("}")
    out.append("")

    out.append("export function decodeStream(value: xdr.ScVal): Stream {")
    out.append("  const native = asNative(value) as Record<string, unknown>;")
    out.append("  if (native === null || typeof native !== \"object\" || native.id === undefined) {")
    out.append("    throw new Error(\"decodeStream: expected a Stream map\");")
    out.append("  }")
    out.append("  const status = STREAM_STATUS_BY_VALUE[Number(native.status)];")
    out.append("  if (!status) throw new Error(`unknown StreamStatus ${String(native.status)}`);")
    out.append("  return {")
    out.append("    id: BigInt(native.id as bigint),")
    out.append("    sender: String(native.sender),")
    out.append("    recipient: String(native.recipient),")
    out.append("    token: String(native.token),")
    out.append("    deposit: BigInt(native.deposit as bigint),")
    out.append("    withdrawn: BigInt(native.withdrawn as bigint),")
    out.append("    startTime: BigInt(native.start_time as bigint),")
    out.append("    endTime: BigInt(native.end_time as bigint),")
    out.append("    cancelable: Boolean(native.cancelable),")
    out.append("    status,")
    out.append("  };")
    out.append("}")
    out.append("")

    out.append("export function encodeCreateStreamArgs(args: CreateStreamArgs): xdr.ScVal[] {")
    out.append("  return [")
    out.append("    addressToScVal(args.sender),")
    out.append("    addressToScVal(args.recipient),")
    out.append("    addressToScVal(args.token),")
    out.append("    nativeToScVal(asBigInt(args.depositAmount, \"depositAmount\"), { type: \"i128\" }),")
    out.append("    nativeToScVal(asBigInt(args.startTime, \"startTime\"), { type: \"u64\" }),")
    out.append("    nativeToScVal(asBigInt(args.endTime, \"endTime\"), { type: \"u64\" }),")
    out.append("    nativeToScVal(args.cancelable),")
    out.append("  ];")
    out.append("}")
    out.append("")
    for function in SPEC["functions"]:
        if function["name"] == "create_stream":
            continue
        args_name = pascal(function["name"]) + "Args"
        fn = camel(function["name"])
        out.append(
            f"export function encode{pascal(function['name'])}Args(args: {args_name}): xdr.ScVal[] {{"
        )
        out.append("  return [")
        for arg in function["args"]:
            field = f"args.{camel(arg['name'])}"
            if arg["type"] == "address":
                out.append(f"    addressToScVal({field}),")
            elif arg["type"] == "i128":
                out.append(
                    f'    nativeToScVal(asBigInt({field}, "{camel(arg["name"])}"), {{ type: "i128" }}),'
                )
            elif arg["type"] == "u64":
                out.append(
                    f'    nativeToScVal(asBigInt({field}, "{camel(arg["name"])}"), {{ type: "u64" }}),'
                )
            elif arg["type"] == "u32":
                out.append(f"    nativeToScVal(Number({field}), {{ type: \"u32\" }}),")
            elif arg["type"] == "bool":
                out.append(f"    nativeToScVal({field}),")
            else:
                raise ValueError(f"cannot encode TS arg type {arg['type']}")
        out.append("  ];")
        out.append("}")
        out.append("")

    # Result decoders.
    for function in SPEC["functions"]:
        name = camel(function["name"])
        returns = function["returns"]
        ret_ts = ts_type(returns)
        out.append(
            f"export function decode{pascal(function['name'])}Result(value: xdr.ScVal): {ret_ts} {{"
        )
        if returns == "void":
            out.append("  void value;")
            out.append("  return undefined;")
        elif returns in ("u64", "i128"):
            out.append(
                f'  return asBigIntResult(value, "{function["name"]} result");'
            )
        elif returns == "Stream":
            out.append("  return decodeStream(value);")
        elif isinstance(returns, dict) and "vec" in returns:
            out.append("  const native = asNative(value);")
            out.append("  if (!Array.isArray(native)) throw new Error(`" + function["name"] + ": expected an array`);")
            out.append("  return native.map((item) => BigInt(item as bigint));")
        else:
            raise ValueError(f"cannot decode TS return type {returns}")
        out.append("}")
        out.append("")

    # Events.
    out.append("export interface EventBase {")
    out.append("  contractId: string;")
    out.append("}")
    out.append("")
    for event in SPEC["events"]:
        out.append(f"export interface {event['name']}Event extends EventBase {{")
        out.append(f'  type: "{event["name"]}";')
        for field in event["topicFields"] + event["dataFields"]:
            out.append(f"  {camel(field['name'])}: {ts_type(field['type'])};")
        out.append("}")
        out.append("")
    names = " | ".join(f"{event['name']}Event" for event in SPEC["events"])
    out.append(f"export type StreamPayEvent = {names};")
    out.append("")

    out.append("function eventContractId(event: xdr.ContractEvent): string {")
    out.append("  type ContractIdLike = { value: Uint8Array };")
    out.append("  const raw = (event as unknown as { contractId?: ContractIdLike }).contractId;")
    out.append("  if (!raw) throw new Error(\"event has no contract id\");")
    out.append("  return StrKey.encodeContract(Buffer.from(raw.value));")
    out.append("}")
    out.append("")
    out.append("function topicValue(topics: xdr.ScVal[], index: number, name: string): xdr.ScVal {")
    out.append("  const value = topics[index];")
    out.append("  if (value === undefined) throw new Error(`event ${name} is missing topic ${index}`);")
    out.append("  return value;")
    out.append("}")
    out.append("")
    out.append("function dataValue(data: Record<string, unknown>, name: string): unknown {")
    out.append("  if (!(name in data)) throw new Error(`event data is missing field ${name}`);")
    out.append("  return data[name];")
    out.append("}")
    out.append("")
    out.append("function asString(value: unknown, label: string): string {")
    out.append("  if (typeof value !== \"string\") throw new Error(`${label}: expected a string`);")
    out.append("  return value;")
    out.append("}")
    out.append("")
    out.append("function asBool(value: unknown, label: string): boolean {")
    out.append("  if (typeof value !== \"boolean\") throw new Error(`${label}: expected a bool`);")
    out.append("  return value;")
    out.append("}")
    out.append("")
    out.append("function asEventBigInt(value: unknown, label: string): bigint {")
    out.append("  if (typeof value !== \"bigint\" && typeof value !== \"number\") {")
    out.append("    throw new Error(`${label}: expected an integer`);")
    out.append("  }")
    out.append("  return BigInt(value);")
    out.append("}")
    out.append("")

    out.append("/** Decodes a StreamPay contract event; `null` for foreign events. */")
    out.append("export function decodeStreamPayEvent(event: xdr.ContractEvent): StreamPayEvent | null {")
    out.append("  const type = (event as unknown as { type?: { name?: string } }).type;")
    out.append("  if (type?.name !== \"contract\") return null;")
    out.append("  const body = (event as unknown as { body?: { v0?: { topics: xdr.ScVal[]; data: xdr.ScVal } } }).body;")
    out.append("  if (!body?.v0) throw new Error(\"unsupported ContractEvent body\");")
    out.append("  const topics = body.v0.topics;")
    out.append("  const name = asString(asNative(topicValue(topics, 0, \"<unknown>\")), \"event name\");")
    out.append("  const contractId = eventContractId(event);")
    out.append("  const data = asNative(body.v0.data) as Record<string, unknown>;")
    out.append("  switch (name) {")
    for event in SPEC["events"]:
        out.append(f'    case "{event["topic"]}": {{')
        out.append("      return {")
        out.append(f'        type: "{event["name"]}",')
        out.append("        contractId,")
        index = 1
        for field in event["topicFields"]:
            label = f'"{event["name"]}.{field["name"]}"'
            if field["type"] in ("u64", "i128"):
                expr = f"asEventBigInt(asNative(topicValue(topics, {index}, \"{event['topic']}\")), {label})"
            elif field["type"] == "bool":
                expr = f"asBool(asNative(topicValue(topics, {index}, \"{event['topic']}\")), {label})"
            else:
                expr = f"asString(asNative(topicValue(topics, {index}, \"{event['topic']}\")), {label})"
            out.append(f"        {camel(field['name'])}: {expr},")
            index += 1
        for field in event["dataFields"]:
            label = f'"{event["name"]}.{field["name"]}"'
            value = f'dataValue(data, "{field["name"]}")'
            if field["type"] in ("u64", "i128"):
                expr = f"asEventBigInt({value}, {label})"
            elif field["type"] == "bool":
                expr = f"asBool({value}, {label})"
            elif field["type"] == "address":
                expr = f"asString({value}, {label})"
            else:
                raise ValueError(f"cannot decode event field type {field['type']}")
            out.append(f"        {camel(field['name'])}: {expr},")
        out.append("      };")
        out.append("    }")
    out.append("    default:")
    out.append("      return null;")
    out.append("  }")
    out.append("}")
    out.append("")

    out.append("export const CONTRACT_ERRORS: Readonly<Record<number, string>> = {")
    for error in SPEC["errors"]:
        out.append(f"  {error['code']}: \"{error['name']}\",")
    out.append("};")
    out.append("")
    out.append("export function contractErrorName(code: number): string | undefined {")
    out.append("  return CONTRACT_ERRORS[code];")
    out.append("}")
    out.append("")
    out.append("/** Extracts a `StreamError` code from simulation/submission error text. */")
    out.append("export function contractErrorFromMessage(message: string): number | undefined {")
    out.append("  const match = message.match(/Error\\(Contract, #(\\d+)\\)/);")
    out.append("  return match ? Number(match[1]) : undefined;")
    out.append("}")
    out.append("")
    out.append("export interface FunctionSpec {")
    out.append("  name: string;")
    out.append("  argNames: readonly string[];")
    out.append("  argTypes: readonly string[];")
    out.append("  returnType: string;")
    out.append("  mutating: boolean;")
    out.append("}")
    out.append("")
    out.append("export const FUNCTIONS: readonly FunctionSpec[] = [")
    for function in SPEC["functions"]:
        arg_names = ", ".join(f'"{a["name"]}"' for a in function["args"])
        arg_types = ", ".join(
            f'"{("vec:" + a["type"]["vec"]) if isinstance(a["type"], dict) else a["type"]}"'
            for a in function["args"]
        )
        returns = function["returns"]
        return_type = (
            "vec:" + returns["vec"] if isinstance(returns, dict) else returns
        )
        out.append("  {")
        out.append(f'    name: "{function["name"]}",')
        out.append(f"    argNames: [{arg_names}],")
        out.append(f"    argTypes: [{arg_types}],")
        out.append(f'    returnType: "{return_type}",')
        out.append(f"    mutating: {str(function['mutating']).lower()},")
        out.append("  },")
    out.append("];")
    out.append("")
    return "\n".join(out)


