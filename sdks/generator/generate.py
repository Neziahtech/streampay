def generate_python() -> str:
    out: list[str] = [
        PY_HEADER.format(fingerprint=FINGERPRINT),
        '"""Generated StreamPay bindings. Regenerate with make -C sdks generate."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from enum import IntEnum",
        "from typing import Any",
        "",
        "from .xdr import (",
        "    ContractEvent,",
        "    address_to_scval,",
        "    bool_to_scval,",
        "    i128_to_scval,",
        "    scval_to_address,",
        "    scval_to_bool,",
        "    scval_to_i128,",
        "    scval_to_struct,",
        "    scval_to_u32,",
        "    scval_to_u64,",
        "    u32_to_scval,",
        "    u64_to_scval,",
        ")",
        "",
        f'SPEC_FINGERPRINT = "{FINGERPRINT}"',
        f'CONTRACT_VERSION = "{SPEC["contract"]["version"]}"',
    ]
    for name, constant in SPEC["constants"].items():
        out.append(f"{name} = {constant['value']}")
    out.append("")

    out.append("METHODS = {")
    for function in SPEC["functions"]:
        out.append(f'    "{camel(function["name"])}": "{function["name"]}",')
    out.append("}")
    out.append("")

    for enum in SPEC["enums"]:
        out.append("")
        out.append(f"class {enum['name']}(IntEnum):")
        for case in enum["cases"]:
            out.append(f"    {case['name'].upper()} = {case['value']}")
        out.append("")

    out.append("")
    out.append("@dataclass(frozen=True)")
    out.append("class Stream:")
    for field in SPEC["structs"][0]["fields"]:
        py = py_type(field["type"])
        out.append(f"    {field['name']}: {py}")
    out.append("")
    out.append("    @classmethod")
    out.append("    def from_native(cls, value: Any) -> \"Stream\":")
    out.append("        fields = scval_to_struct(value)")
    out.append("        return cls(")
    for field in SPEC["structs"][0]["fields"]:
        name = field["name"]
        t = field["type"]
        if t == "StreamStatus":
            expr = f"StreamStatus(scval_to_u32(fields[\"{name}\"]))"
        elif t == "address":
            expr = f"scval_to_address(fields[\"{name}\"])"
        elif t == "i128":
            expr = f"scval_to_i128(fields[\"{name}\"])"
        elif t == "u64":
            expr = f"scval_to_u64(fields[\"{name}\"])"
        elif t == "bool":
            expr = f"scval_to_bool(fields[\"{name}\"])"
        else:
            raise ValueError(f"cannot decode Python field type {t}")
        out.append(f"            {name}={expr},")
    out.append("        )")
    out.append("")

    out.append("")
    out.append("@dataclass(frozen=True)")
    out.append("class CreateStreamArgs:")
    out.append("    sender: str")
    out.append("    recipient: str")
    out.append("    token: str")
    out.append("    deposit_amount: int")
    out.append("    start_time: int")
    out.append("    end_time: int")
    out.append("    cancelable: bool")
    out.append("")
    out.append("    def to_scvals(self) -> list[Any]:")
    out.append("        return [")
    out.append("            address_to_scval(self.sender),")
    out.append("            address_to_scval(self.recipient),")
    out.append("            address_to_scval(self.token),")
    out.append("            i128_to_scval(self.deposit_amount),")
    out.append("            u64_to_scval(self.start_time),")
    out.append("            u64_to_scval(self.end_time),")
    out.append("            bool_to_scval(self.cancelable),")
    out.append("        ]")
    out.append("")

    for function in SPEC["functions"]:
        name = function["name"]
        if name == "create_stream":
            continue
        args_name = pascal(name) + "Args"
        out.append("")
        out.append("@dataclass(frozen=True)")
        out.append(f"class {args_name}:")
        for arg in function["args"]:
            out.append(f"    {arg['name']}: {py_type(arg['type'])}")
        out.append("")
        out.append("    def to_scvals(self) -> list[Any]:")
        out.append("        return [")
        for arg in function["args"]:
            t = arg["type"]
            field = f"self.{arg['name']}"
            if t == "address":
                out.append(f"            address_to_scval({field}),")
            elif t == "i128":
                out.append(f"            i128_to_scval({field}),")
            elif t == "u64":
                out.append(f"            u64_to_scval({field}),")
            elif t == "u32":
                out.append(f"            u32_to_scval({field}),")
            elif t == "bool":
                out.append(f"            bool_to_scval({field}),")
            else:
                raise ValueError(f"cannot encode Python arg type {t}")
        out.append("        ]")
        out.append("")

    # Events.
    for event in SPEC["events"]:
        out.append("")
        out.append("@dataclass(frozen=True)")
        out.append(f"class {event['name']}Event:")
        out.append("    contract_id: str")
        for field in event["topicFields"] + event["dataFields"]:
            out.append(f"    {field['name']}: {py_type(field['type'])}")
    out.append("")
    out.append("")
    out.append("StreamPayEvent = " + " | ".join(f"{e['name']}Event" for e in SPEC["events"]))
    out.append("")
    out.append("")
    out.append("def decode_event(event: ContractEvent) -> StreamPayEvent | None:")
    out.append('    """Decodes a StreamPay event; ``None`` for foreign events."""')
    for event in SPEC["events"]:
        cond = "if" if event is SPEC["events"][0] else "elif"
        out.append(f'    {cond} event.name == "{event["topic"]}":')
        out.append(f"        return {event['name']}Event(")
        out.append("            contract_id=event.contract,")
        index = 0
        for field in event["topicFields"]:
            name = field["name"]
            t = field["type"]
            expr = {
                "u64": f"scval_to_u64(event.topics[{index}])",
                "i128": f"scval_to_i128(event.topics[{index}])",
                "address": f"scval_to_address(event.topics[{index}])",
                "bool": f"scval_to_bool(event.topics[{index}])",
            }[t]
            out.append(f"            {name}={expr},")
            index += 1
        # Reuse the parsed topics; data fields come from the event's map.
        out.append("            **{")
        for field in event["dataFields"]:
            name = field["name"]
            t = field["type"]
            expr = {
                "u64": f"scval_to_u64(event.data[\"{name}\"])",
                "i128": f"scval_to_i128(event.data[\"{name}\"])",
                "address": f"scval_to_address(event.data[\"{name}\"])",
                "bool": f"scval_to_bool(event.data[\"{name}\"])",
            }[t]
            out.append(f'                "{name}": {expr},')
        out.append("            },")
        out.append("        )")
    out.append("    return None")
    out.append("")

    # Errors.
    out.append("")
    out.append("class StreamError(IntEnum):")
    for error in SPEC["errors"]:
        out.append(f"    {error['name'].upper()} = {error['code']}")
    out.append("")
    out.append("")
    out.append("CONTRACT_ERROR_NAMES = {")
    for error in SPEC["errors"]:
        out.append(f'    {error["code"]}: "{error["name"]}",')
    out.append("}")
    out.append("")
    out.append("")
    out.append("def contract_error(code: int) -> StreamError | None:")
    out.append("    try:")
    out.append("        return StreamError(code)")
    out.append("    except ValueError:")
    out.append("        return None")
    out.append("")
    out.append("")
    out.append("def contract_error_name(code: int) -> str | None:")
    out.append("    return CONTRACT_ERROR_NAMES.get(code)")
    out.append("")

    # Result decoders.
    for function in SPEC["functions"]:
        name = function["name"]
        returns = function["returns"]
        out.append("")
        out.append(f"def decode_{name}_result(value: Any):")
        if returns == "void":
            out.append("    return None")
        elif returns == "Stream":
            out.append("    return Stream.from_native(value)")
        elif returns == "i128":
            out.append("    return scval_to_i128(value)")
        elif returns == "u64":
            out.append("    return scval_to_u64(value)")
        elif isinstance(returns, dict) and "vec" in returns:
            out.append("    return [scval_to_u64(item) for item in value.value]")
        else:
            raise ValueError(f"cannot decode Python return type {returns}")
        out.append("")

    out.append("")
    out.append("FUNCTIONS = [")
    for function in SPEC["functions"]:
        args = ", ".join(f'"{a["name"]}"' for a in function["args"])
        types = ", ".join(
            f'"{("vec:" + a["type"]["vec"]) if isinstance(a["type"], dict) else a["type"]}"'
            for a in function["args"]
        )
        returns = function["returns"]
        return_type = (
            "vec:" + returns["vec"] if isinstance(returns, dict) else returns
        )
        out.append("    {")
        out.append(f'        "name": "{function["name"]}",')
        out.append(f'        "arg_names": [{args}],')
        out.append(f'        "arg_types": [{types}],')
        out.append(f'        "return_type": "{return_type}",')
        out.append(f'        "mutating": {function["mutating"]},')
        out.append("    },")
    out.append("]")
    out.append("")
    return "\n".join(out)


def format_rust(source: str) -> str:
    """Formats generated Rust with rustfmt so `cargo fmt --check` stays green.

    Regeneration is part of the contract change workflow, and the repository
    already requires rustfmt for the contract, so this is not an extra tool.
    """
    try:
        result = subprocess.run(
            ["rustfmt", "--edition", "2021", "--emit", "stdout"],
            input=source,
            text=True,
            capture_output=True,
            check=False,
        )
    except FileNotFoundError as error:
        raise SystemExit(
            "rustfmt is required to regenerate the Rust SDK: rustup component add rustfmt"
        ) from error
    if result.returncode != 0:
        raise SystemExit(f"rustfmt failed:\n{result.stderr}")
    return result.stdout


FILES = {
    ROOT / "sdks" / "rust" / "src" / "generated.rs": lambda: format_rust(generate_rust()),
    ROOT / "sdks" / "typescript" / "src" / "generated.ts": generate_typescript,
    ROOT / "sdks" / "python" / "streampay" / "_generated.py": generate_python,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    stale = []
    for path, generator in FILES.items():
        expected = generator()
        if not expected.endswith("\n"):
            expected += "\n"
        if args.check:
            actual = path.read_text() if path.exists() else ""
            if actual != expected:
                diff = "".join(
                    difflib.unified_diff(
                        actual.splitlines(True),
                        expected.splitlines(True),
                        fromfile=str(path),
                        tofile=str(path) + " (regenerated)",
                        n=2,
                    )
                )
                print(diff, file=sys.stderr)
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        print(
            "generated SDK sources are stale; run: python3 sdks/generator/generate.py",
            file=sys.stderr,
        )
        return 1
    print(f"spec sha256 {FINGERPRINT[:12]}… — generated clients are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
